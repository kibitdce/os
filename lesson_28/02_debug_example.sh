#!/bin/bash
# Запуск з флагом -x виводить кожну команду перед виконанням
bash -x 02_hello.sh

# Або додати set -x всередині скрипту:
#!/bin/bash
set -x   # увімкнути debug
echo "test"
set +x   # вимкнути debug

# set -e  — зупинити скрипт при будь-якій помилці (рекомендовано!)
# set -u  — помилка при використанні незаданих змінних
# set -o pipefail — помилка при падінні в pipe
set -euo pipefail  # золотий стандарт надійного скрипту